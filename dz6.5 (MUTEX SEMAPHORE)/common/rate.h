// Швидкість конвеєра (ДЗ 6.5). Без FreeRTOS: значення лічильника передає виклик.
//
// Швидкість рахується за останні RATE_WINDOW_S секунд: різниця лічильника за вікно,
// перерахована на хвилину. Перші 10 с вікно коротше: стільки секунд, скільки минуло.
// Результат - у десятих частках деталі/хв, щоб показати один знак після коми без float.
#ifndef DZ65_RATE_H
#define DZ65_RATE_H

#include <stdint.h>

#define RATE_WINDOW_S UINT32_C(10)

typedef struct {
  uint32_t past[RATE_WINDOW_S];  // лічильник 1..10 с тому, кільцевий буфер
  uint32_t head;                 // найстаріше значення
  uint32_t seconds;              // довжина вікна зараз, від 1 до RATE_WINDOW_S
} rate_t;

// start - значення лічильника в момент старту.
void rate_init(rate_t *r, uint32_t start);

// Викликати раз на секунду з поточним значенням лічильника. Повертає деталі/хв × 10.
uint32_t rate_update(rate_t *r, uint32_t count);

#endif
